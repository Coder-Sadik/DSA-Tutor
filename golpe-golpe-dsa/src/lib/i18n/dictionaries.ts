import { Locale } from './config';

export function formatNumber(num: number | string, lang: Locale): string {
  if (lang === 'bn') {
    const parsed = Number(num);
    return isNaN(parsed) ? String(num) : parsed.toLocaleString('bn-BD');
  }
  return String(num);
}

